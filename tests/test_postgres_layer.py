"""The Postgres adapter (pg.py) that lets the SQLite-style SQL run on Neon.
SQL translation and row behaviour are checked always; the setup race and the write lock need a
real Postgres (set TEST_DATABASE_URL)."""
import threading
import time
import unittest
from types import SimpleNamespace

import pg
from support import PG_URL, fresh_db

import db as dbmod


class TranslateTests(unittest.TestCase):
    def test_placeholders_percent_signs_and_quoted_text(self):
        sql, returns_id = pg.translate("SELECT * FROM x WHERE a = ? AND b LIKE '%?%' AND c = 'it''s ?' AND d = ?")
        self.assertEqual(sql, "SELECT * FROM x WHERE a = %s AND b ILIKE '%%?%%' AND c = 'it''s ?' AND d = %s")
        self.assertFalse(returns_id)

    def test_case_insensitive_like_and_nocase(self):
        self.assertEqual(pg.translate("SELECT 1 FROM t WHERE name NOT LIKE ?")[0], "SELECT 1 FROM t WHERE name NOT ILIKE %s")
        self.assertEqual(pg.translate("SELECT 1 FROM users WHERE u.email = ? COLLATE NOCASE AND id <> ?")[0],
                         "SELECT 1 FROM users WHERE lower(u.email) = lower(%s) AND id <> %s")

    def test_inserts_return_ids(self):
        sql, rid = pg.translate("INSERT INTO users (name) VALUES (?)")
        self.assertEqual((sql, rid), ("INSERT INTO users (name) VALUES (%s) RETURNING id", True))
        for table in ("settings", "pages", "uploads"):                      # no id column
            sql, rid = pg.translate("INSERT INTO %s (a) VALUES (?)" % table)
            self.assertFalse(rid)
            self.assertNotIn("RETURNING", sql)
        sql, rid = pg.translate("INSERT INTO spins (a) VALUES (?) RETURNING id")
        self.assertEqual(sql.count("RETURNING"), 1)
        sql, rid = pg.translate("INSERT OR IGNORE INTO voucher_codes (package_id, code) VALUES (?, ?)")
        self.assertEqual(sql, "INSERT INTO voucher_codes (package_id, code) VALUES (%s, %s) ON CONFLICT DO NOTHING RETURNING id")

    def test_schema_translation(self):
        out = pg.translate_schema("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT UNIQUE COLLATE NOCASE, "
                                  "data BLOB);\nCREATE UNIQUE INDEX i ON t(email COLLATE NOCASE);")
        self.assertIn("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
        self.assertIn("ON t(lower(email))", out)
        self.assertIn("data BYTEA", out)
        self.assertNotIn("NOCASE", out)
        self.assertIn("uq_users_email_ci ON users (lower(email))", out)

    def test_rows_behave_like_sqlite_rows(self):
        cursor = SimpleNamespace(description=[SimpleNamespace(name=n) for n in ("id", "name", "id")])
        row = pg._row_factory(cursor)((7, "Rahim", 99))
        self.assertEqual((row[0], row["name"], row["id"], row[-1]), (7, "Rahim", 7, 99))   # duplicate name: first wins
        self.assertEqual(row.keys(), ["id", "name", "id"])
        self.assertEqual(dict(row), {"id": 7, "name": "Rahim"})
        self.assertEqual(list(row), [7, "Rahim", 99])
        with self.assertRaises(IndexError):
            row["missing"]
        same = pg._row_factory(cursor)((7, "Rahim", 99))
        self.assertEqual(row, same)
        self.assertEqual(hash(row), hash(same))


@unittest.skipUnless(PG_URL, "set TEST_DATABASE_URL to run the Postgres-only tests")
class PostgresTests(unittest.TestCase):
    @classmethod
    def tearDownClass(cls):
        fresh_db()                                                          # leave a normal database behind

    def test_first_start_race_seeds_once(self):
        import psycopg
        with psycopg.connect(PG_URL, autocommit=True) as c:
            c.execute("DROP SCHEMA public CASCADE")
            c.execute("CREATE SCHEMA public")
        errors = []

        def start():
            try:
                dbmod.init_db(PG_URL)
            except Exception as e:
                errors.append(repr(e))

        threads = [threading.Thread(target=start) for _ in range(8)]
        for t in threads:
            t.start()
        for t in threads:
            t.join()
        self.assertEqual(errors, [])
        c = dbmod.connect(PG_URL)
        try:
            self.assertEqual(c.execute("SELECT COUNT(*) FROM categories").fetchone()[0], 3)
            self.assertEqual(c.execute("SELECT COUNT(*) FROM products").fetchone()[0], 7)
            self.assertEqual(c.execute("SELECT value FROM settings WHERE key = '_schema_version'").fetchone()[0],
                             dbmod.schema_version())
        finally:
            c.close()
        t0 = time.time()
        dbmod.init_db(PG_URL)                                               # already set up: skipped quickly
        self.assertLess(time.time() - t0, 2)

    def test_write_transactions_run_one_at_a_time(self):
        fresh_db()
        a, b = dbmod.connect(PG_URL), dbmod.connect(PG_URL)
        waited = {}
        try:
            a.execute("BEGIN IMMEDIATE")

            def second():
                t0 = time.time()
                b.execute("BEGIN IMMEDIATE")
                waited["s"] = time.time() - t0
                b.execute("ROLLBACK")

            t = threading.Thread(target=second)
            t.start()
            time.sleep(0.6)
            a.execute("ROLLBACK")
            t.join()
        finally:
            a.close()
            b.close()
        self.assertGreater(waited["s"], 0.5)
